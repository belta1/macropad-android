package dev.belta.macropad.hid

/** The HID report descriptor and builders for the three input reports. Pure Kotlin, unit-tested. */
object HidReports {
    const val ID_KEYBOARD: Byte = 1
    const val ID_CONSUMER: Byte = 2
    const val ID_MOUSE: Byte = 3

    /** Report map. Report IDs are not part of the notification payloads (HOGP uses Report Reference). */
    val DESCRIPTOR: ByteArray = intArrayOf(
        // Keyboard, ID 1: [modifiers, reserved, key1..key6]; output report = LEDs
        0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, 0x01,
        0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
        0x95, 0x01, 0x75, 0x08, 0x81, 0x01,
        0x95, 0x05, 0x75, 0x01, 0x05, 0x08, 0x19, 0x01, 0x29, 0x05, 0x91, 0x02,
        0x95, 0x01, 0x75, 0x03, 0x91, 0x01,
        0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x26, 0xFF, 0x00, 0x05, 0x07, 0x19, 0x00, 0x29, 0xFF, 0x81, 0x00,
        0xC0,
        // Consumer control, ID 2: one 16-bit usage
        0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01, 0x85, 0x02,
        0x15, 0x00, 0x26, 0xFF, 0x03, 0x19, 0x00, 0x2A, 0xFF, 0x03, 0x75, 0x10, 0x95, 0x01, 0x81, 0x00,
        0xC0,
        // Mouse, ID 3: [buttons, x, y, wheel, horizontal pan]
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x03, 0x09, 0x01, 0xA1, 0x00,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02,
        0x95, 0x01, 0x75, 0x05, 0x81, 0x03,
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06,
        0x05, 0x0C, 0x0A, 0x38, 0x02, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x01, 0x81, 0x06,
        0xC0, 0xC0,
    ).map { it.toByte() }.toByteArray()

    fun keyboard(mods: Int, keys: List<Int>): ByteArray {
        val report = ByteArray(8)
        report[0] = mods.toByte()
        keys.take(6).forEachIndexed { i, k -> report[2 + i] = k.toByte() }
        return report
    }

    fun consumer(usage: Int) = byteArrayOf((usage and 0xFF).toByte(), (usage shr 8 and 0xFF).toByte())

    fun mouse(buttons: Int, dx: Int, dy: Int, wheel: Int = 0, pan: Int = 0) = byteArrayOf(
        buttons.toByte(), clamp(dx), clamp(dy), clamp(wheel), clamp(pan),
    )

    private fun clamp(v: Int) = v.coerceIn(-127, 127).toByte()
}
